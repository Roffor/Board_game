"""Черновые карты для прогона: Маг-колдун, Жрец, враги и комнаты Беззвёздных катакомб.
Все числа черновые. Функция эффекта: fn(g, h, off) — g игра, h ключ героя ('M'/'P'),
off — сколько раз срабатывает Подношение (0, 1 или 2 с легендаркой)."""


class Card:
    def __init__(self, cid, name, hero, kind, text, opts, cost=0, offering=False,
                 value=5, tags=(), branch=None):
        self.cid, self.name, self.hero, self.kind, self.text = cid, name, hero, kind, text
        self.opts = opts            # список (метка, fn)
        self.cost = cost
        self.offering = offering    # есть строка Подношения
        self.value = value          # насколько жалко изгнать/сбросить
        self.tags = set(tags)
        self.branch = branch

    def __repr__(self):
        return self.name


