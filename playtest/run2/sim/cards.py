class Card:
    def __init__(self, cid, name, hero, kind, text, opts, cost=0, offering=False,
                 value=5, tags=(), branch=None):
        self.cid, self.name, self.hero, self.kind, self.text = cid, name, hero, kind, text
        self.opts = opts
        self.cost = cost
        self.offering = offering
        self.value = value
        self.tags = set(tags)
        self.branch = branch

    def __repr__(self):
        return self.name


